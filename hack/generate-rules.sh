# Create placeholder rules when mixins aren't available
create_placeholder_rules() {
    log_info "Creating placeholder rule templates..."
    
    # Kubernetes alerts placeholder
    if [[ ! -f "${RULES_OUTPUT_DIR}/kubernetes-alerts.yaml" ]]; then
        cat > "${RULES_OUTPUT_DIR}/kubernetes-alerts.yaml" << 'EOF'
{{- if and .Values.mixins.enabled .Values.mixins.kubernetes.alerts }}
# Kubernetes Alert Rules - Placeholder
# Run 'make sync-mixins' to generate rules from kubernetes-mixin
apiVersion: v1
kind: ConfigMap
metadata:
  name: {{ include "k8s-observability-stack.fullname" . }}-kubernetes-alerts
  namespace: {{ include "k8s-observability-stack.namespace" . }}
  labels:
    {{- include "k8s-observability-stack.labels" . | nindent 4 }}
data:
  alerts.yaml: |
    groups: []
{{- end }}
EOF
    fi
    
    # Kubernetes rules placeholder
    if [[ ! -f "${RULES_OUTPUT_DIR}/kubernetes-rules.yaml" ]]; then
        cat > "${RULES_OUTPUT_DIR}/kubernetes-rules.yaml" << 'EOF'
{{- if and .Values.mixins.enabled .Values.mixins.kubernetes.enabled }}
# Kubernetes Recording Rules - Placeholder
# Run 'make sync-mixins' to generate rules from kubernetes-mixin
apiVersion: v1
kind: ConfigMap
metadata:
  name: {{ include "k8s-observability-stack.fullname" . }}-kubernetes-rules
  namespace: {{ include "k8s-observability-stack.namespace" . }}
  labels:
    {{- include "k8s-observability-stack.labels" . | nindent 4 }}
data:
  rules.yaml: |
    groups: []
{{- end }}
EOF
    fi
    
    # Node alerts placeholder
    if [[ ! -f "${RULES_OUTPUT_DIR}/node-alerts.yaml" ]]; then
        cat > "${RULES_OUTPUT_DIR}/node-alerts.yaml" << 'EOF'
{{- if and .Values.mixins.enabled .Values.mixins.nodeExporter.alerts }}
# Node Exporter Alert Rules - Placeholder
# Run 'make sync-mixins' to generate rules from node-mixin
apiVersion: v1
kind: ConfigMap
metadata:
  name: {{ include "k8s-observability-stack.fullname" . }}-node-alerts
  namespace: {{ include "k8s-observability-stack.namespace" . }}
  labels:
    {{- include "k8s-observability-stack.labels" . | nindent 4 }}
data:
  alerts.yaml: |
    groups: []
{{- end }}
EOF
    fi
}

# Main execution
main() {
    log_info "Starting rules generation..."
    
    check_dependencies
    setup_directories
    
    # Check if mixins are installed
    if [[ -d "${MIXINS_DIR}/vendor" ]]; then
        create_rules_jsonnet
        generate_kubernetes_alerts
        generate_kubernetes_rules
        generate_node_alerts
    else
        log_warn "Mixin vendor directory not found."
        log_info "Creating placeholder templates. Run 'make sync-mixins' to generate real rules."
        create_placeholder_rules
    fi
    
    log_info ""
    log_info "Rules generation completed!"
    log_info "Output directory: ${RULES_OUTPUT_DIR}"
}

main "$@"
